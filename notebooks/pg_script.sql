    IF in_bunji LIKE '%*%' THEN
        query_str := 'SELECT * FROM "건축물대장" WHERE "시군구명" = $1 AND "번지" = $2';
    ELSE
        -- input_1에 '%'를 붙여 LIKE 검색용 파라미터 생성
        query_str := 'SELECT * FROM "건축물대장" WHERE "대지_위치" LIKE CONCAT($1, '' '', $2, ''%'')';
    END IF;

	FOR rec IN EXECUTE query_str USING in_sigungu, in_bunji
	LOOP
		---------------------------------------------
		-- 1. 번지 매핑
		---------------------------------------------
		"건축물대장_PK" := rec."관리_건축물대장_PK";
		"건물_도로명_주소" := rec."도로명_대지_위치";
		"건물_대지_주소" := rec."대지_위치";
		"건물_주용도" := rec."주_용도_코드_명";
		"건물_기타용도" := rec."기타_용도";
		"건물_대지면적" := rec."대지_면적";
		"건물_연면적" := rec."연면적";
		---------------------------------------------
		-- 2. 도로 매핑
		---------------------------------------------
		IF rec."도로명_대지_위치" LIKE CONCAT('%', in_doro, '%') THEN
			"도로매핑" := 1;
		ELSE
			"도로매핑" := 0;
		END IF;
		---------------------------------------------
		-- 3. 용도 매핑
		---------------------------------------------
		IF "건물_주용도" LIKE '%근린생활시설%' THEN 
			"용도매핑" := 0;
		ELSIF "건물_주용도" in ('단독주택', '공동주택') then
			"용도매핑" := 0;
		ELSE
			"용도매핑" := 1;
		END IF;
		---------------------------------------------
		-- 4. 면적 매핑
		---------------------------------------------
		if in_total_area = rec."연면적" then
			"면적매핑" := 1;
		elsif trunc(in_total_area) = trunc(rec."연면적") then
			"면적매핑" := 0.5;
		elsif round(in_total_area) = round(rec."연면적") then
			"면적매핑" := 0.3;
		else
			"면적매핑" := 0;
		END IF;
		-- pipe
		RETURN NEXT;
	END LOOP;
	RETURN;
END;
$$ LANGUAGE plpgsql;




