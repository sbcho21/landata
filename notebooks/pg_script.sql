-- 건축물대장 매핑함수
CREATE OR REPLACE FUNCTION get_bldg_type1 (in_sigungu TEXT, in_bunji TEXT, in_doro TEXT, in_ground_area numeric, in_total_area numeric)
RETURNS TABLE ("건축물대장_PK" text, "건물_도로명_주소" text, "건물_대지_주소" text, "건물_주용도" text, "건물_기타용도" text, "건물_대지면적" numeric, "건물_연면적" numeric, "도로매핑" numeric, "용도매핑" numeric, "면적매핑" numeric) AS $$
DECLARE
	-- 로직에 필요한 변수 선언
    rec RECORD;
BEGIN
	FOR rec IN SELECT * FROM "건축물대장" WHERE "시군구명" = in_sigungu AND "번지" = in_bunji
	LOOP
		---------------------------------------------
		-- 1. 번지 매핑
		---------------------------------------------
		"건축물대장_PK" := rec."관리_건축물대장_PK";
		"건물_도로명_주소" := rec."도로명_대지_위치";
		"건물_대지_주소" := rec."대지_위치";
		"건물_주용도" := rec."주_용도_코드_명";
		"건물_기타용도" := rec."기타_용도";
		"건물_대지면적" := rec."대지_면적";
		"건물_연면적" := rec."연면적";
		---------------------------------------------
		-- 2. 도로 매핑
		---------------------------------------------
		IF rec."도로명_대지_위치" LIKE CONCAT('%', in_doro, '%') THEN
			"도로매핑" := 1;
		ELSE
			"도로매핑" := 0;
		END IF;
		---------------------------------------------
		-- 3. 용도 매핑
		---------------------------------------------
		IF "건물_주용도" = '단독주택' THEN
			"용도매핑" = 1;
		ELSE
			"용도매핑" = 0;
		END IF;
		---------------------------------------------
		-- 4. 면적 매핑
		---------------------------------------------
		if in_ground_area = rec."대지_면적" and in_total_area = rec."연면적" then
			"면적매핑" = 1;
		elsif trunc(in_ground_area) = trunc(rec."대지_면적") and trunc(in_total_area) = trunc(rec."연면적") then
			"면적매핑" = 0.5;
		elsif round(in_ground_area) = round(rec."대지_면적") and round(in_total_area) = round(rec."연면적") then
			"면적매핑" = 0.3;
		else
			"면적매핑" = 0;
		END IF;
		-- pipe
		RETURN NEXT;
	END LOOP;
	RETURN;
END;
$$ LANGUAGE plpgsql;

-- 매핑 쿼리 
SELECT "주택유형", ROUND(AVG("번지매핑건수"),1) as "번지매핑", ROUND(AVG("도로매핑건수"),1) as "도로매핑", ROUND(AVG("용도매핑건수"),1) as "용도매핑", ROUND(AVG("면적매핑건수"),1) as "면적매핑" FROM (     
select "계약년월", "번호", "주택유형", "시군구명", "번지", "도로명", "대지면적", "연면적", "거래금액", "건축물대장_PK", "건물_도로명_주소", "건물_대지_주소", "건물_주용도", "건물_기타용도", "건물_대지면적", "건물_연면적", "번지매핑건수", "도로매핑건수", "용도매핑건수",
       COUNT("건축물대장_PK") over (partition by "계약년월", "번호") as "면적매핑건수",
       ROW_NUMBER() OVER (PARTITION BY "계약년월", "번호") AS "매매별일련번호"      
from  (
		select *, COUNT("건축물대장_PK") over (partition by "계약년월", "번호") as "용도매핑건수",
			   MAX("면적매핑") over (partition by "계약년월", "번호") as "면적매핑점수"
		from   (
				select  *, COUNT("건축물대장_PK") over (partition by "계약년월", "번호") as "도로매핑건수",
				        MAX("용도매핑") over (partition by "계약년월", "번호") as "용도매핑점수"
				from   (
						SELECT  t.*, b.*, 
								COUNT("건축물대장_PK") over (partition by "계약년월", "번호") as "번지매핑건수",
								MAX("도로매핑") over (partition by "계약년월", "번호") as "도로매핑점수"
						FROM    "실거래_단독다가구_분당구" t
						        LEFT JOIN LATERAL get_bldg_type1(t."시군구명", t."번지", t."도로명", t."대지면적", t."연면적") b ON TRUE 
						WHERE   t."거래구분" = '1'
						--AND     t."계약년월" LIKE '201805' and t."번호" = 6603 
						ORDER BY t."계약년월", t."번호"
					   )
				where   "도로매핑점수" IS NULL OR "도로매핑점수" = "도로매핑"
			   )
		WHERE   "용도매핑점수" IS NULL OR "용도매핑점수" = "용도매핑"
		)
where   "면적매핑점수" IS NULL OR "면적매핑점수" = "면적매핑"
) WHERE "매매별일련번호" = 1 GROUP BY "주택유형" 
